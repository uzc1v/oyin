let currentLang = localStorage.getItem('lk_lang') || 'uz';

function t(key) {
  return translations[currentLang][key] || translations.uz[key] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lk_lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  // Re-render current page if app is ready
  if (window.renderCurrentPage) window.renderCurrentPage();
}
